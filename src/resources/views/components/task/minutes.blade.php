  分の数を読みやすい長さの言葉にする（45 → 45分、90 → 1時間30分、60 → 1時間）。
  使い方：<x-task.minutes :value="$task->duration_minutes" />
--}}
@props(['value'])
@php($m = (int) $value)
{{-- 60分以上なら「◯時間◯分」、それより短ければ「◯分」にする（ちょうどの時間なら分は出さない） --}}
@if ($m >= 60){{ intdiv($m, 60) }}時間{{ $m % 60 ? ($m % 60).'分' : '' }}@else{{ $m }}分@endif
