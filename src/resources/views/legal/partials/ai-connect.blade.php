<h3>あなたが自分の AI とつないだとき</h3>
<p>あなたが自分で AI のサービス（例：ChatGPT＝OpenAI、Claude＝Anthropic。どちらも米国の会社）を本アプリとつないだときは、そのサービスから求められたときに、あなたの記録のうち仕事の場面の事件を除くもの（事件のなぞ・手がかり・見立て・予想と答え合わせ・屋根裏の棚）を、そのサービスに渡します。これはあなたの操作によるもので、運営者が選んで送るものではありません。</p>
<ul>
  <li>つなぐ前に、許可の画面で、どのサービスに渡るか（戻る先の住所・会社・国）を確かめていただきます。許可しなければ何も渡りません。</li>
  <li>渡すのは読むためだけです。AI のサービスから、あなたの記録を書き換えたり消したりすることはできません。仕事の場面の事件と、ほかの人の記録と、Google カレンダーから読んだ予定の題名と時刻は渡しません。</li>
  <li>渡したあとの扱いは、そのサービスの利用規約・プライバシーポリシーと、あなたのプランの設定（会話を学習に使うかどうか、記憶の機能など）によります。</li>
  <li>本アプリが預かるのは、つないだ AI のサービスの名前・戻る先の住所・許可した日時と期限だけです。許可の証し（通行証）は番号だけを保存し、中身は保存しません。</li>
  <li>通行証は {{ $tokens['access_minutes'] }} 分、更新の札は {{ $tokens['refresh_days'] }} 日で切れます。取り消したものは毎日消し、期限が切れたものは更新の札の期限を過ぎてから消します。退会すると、許可の記録もすべて消します。</li>
  <li>設定の画面の「{{ config('ai_connect.panel.title') }}」で「{{ config('ai_connect.panel.stop') }}」を押せば、いつでも取り消せます。取り消すと、そのサービスからはすぐに読めなくなります。AI のサービスの側でも、つないだアプリを外せます。</li>
</ul>
<p>事件の画面の「{{ config('ai_connect.copy.button') }}」は、文をあなたの端末に写すだけです。本アプリから AI のサービスへは何も送りません。貼るかどうか、どこに貼るかは、あなたが決めます。</p>
